#!/usr/bin/env python3
"""Turn web/logo.svg into main/logo_img.c, the LVGL image on the device's start screen.

    tools/make_logo.py [size]      (default 80 pixels; needs Inkscape and Pillow)

The generated file is committed, so a normal build needs neither.
"""
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
size = int(sys.argv[1]) if len(sys.argv) > 1 else 80
with tempfile.TemporaryDirectory() as tmp:
    png = Path(tmp) / "logo.png"
    subprocess.run(["inkscape", str(ROOT / "web/logo.svg"), "--export-type=png", f"--export-width={size}",
                    f"--export-filename={png}"], check=True, capture_output=True)
    img = Image.open(png).convert("RGBA")

w, h = img.size
data = bytearray()
for r, g, b, a in img.getdata():
    data += bytes((b, g, r, a))  # LVGL ARGB8888 is B, G, R, A in memory
rows = ",\n".join("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) for i in range(0, len(data), 16))
(ROOT / "main/logo_img.c").write_text(f"""// Generated by tools/make_logo.py from web/logo.svg: do not edit.
#include "lvgl.h"

static const uint8_t data[] = {{
{rows}
}};

const lv_image_dsc_t logo_img = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = {w}, .h = {h}, .stride = {w * 4}}},
    .data_size = sizeof(data),
    .data = data,
}};
""")
print(f"main/logo_img.c: {w}x{h}, {len(data)} bytes", file=sys.stderr)
